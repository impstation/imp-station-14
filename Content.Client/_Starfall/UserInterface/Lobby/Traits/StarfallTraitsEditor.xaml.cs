using System.Linq; // Aurora's Song
using Content.Shared.Traits;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Starfall.UserInterface.Lobby.Traits;

/// <summary>
/// Displays the character's available traits
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class StarfallTraitsEditor : BoxContainer
{
    public Action? RefreshRequested { get; set; } // Aurora's Song

    public StarfallTraitsEditor()
    {
        RobustXamlLoader.Load(this);
        SearchBar.OnTextChanged += _ => RefreshRequested?.Invoke(); // Aurora's Song
    }

    public IEnumerable<TraitPrototype> FilterSearch(IEnumerable<TraitPrototype> traits) // Aurora's Song
    {
        var query = SearchBar.Text.Trim();

        if (query.Length == 0)
            return traits.OrderBy(trait => Loc.GetString(trait.Name));

        var traitList = traits.ToList();
        var nameMatches = traitList
            .Where(trait =>
                trait.ID.Contains(query, StringComparison.OrdinalIgnoreCase) ||
                Loc.GetString(trait.Name).Contains(query, StringComparison.OrdinalIgnoreCase))
            .OrderBy(trait => Loc.GetString(trait.Name))
            .ToList();

        var descriptionMatches = traitList.Where(trait =>
            !nameMatches.Contains(trait) &&
            trait.Description is { } description &&
            Loc.GetString(description).Contains(query, StringComparison.OrdinalIgnoreCase))
            .OrderBy(trait => Loc.GetString(trait.Name));

        return nameMatches.Concat(descriptionMatches);
    }

    public void Clear() // Aurora's Song
    {
        TraitsList.RemoveAllChildren();
    }

    public void ShowNoTraits() // Aurora's Song
    {
        TraitsList.AddChild(new Label
        {
            Text = Loc.GetString("humanoid-profile-editor-no-traits"),
            FontColorOverride = Color.Gray,
        });
    }

    public GridContainer AddCategory(TraitCategoryPrototype? category) // Aurora's Song
    {
        if (category != null)
            AddCategoryHeader(category);

        var traitGrid = new GridContainer
        {
            Columns = 3,
            HorizontalExpand = true,
            HSeparationOverride = 8,
            VSeparationOverride = 8,
        };

        return traitGrid;
    }

    private void AddCategoryHeader(TraitCategoryPrototype category) // Aurora's Song
    {
        TraitsList.AddChild(new PanelContainer
        {
            Margin = new Thickness(0, 10, 0, 6),
            StyleClasses =
            {
                "StarfallTraitHeader",
            },
            Children =
            {
                new Label
                {
                    Text = Loc.GetString(category.Name),
                    StyleClasses =
                    {
                        "StarfallTraitTitle",
                    },
                },
            },
        });
    }

    public void AddTraitGrid(GridContainer traitGrid) // Aurora's Song
    {
        TraitsList.AddChild(traitGrid);
    }

    public void AddPointCounter(int selectionCount, int maximum) // Aurora's Song
    {
        TraitsList.AddChild(new Label
        {
            Text = Loc.GetString(
                "humanoid-profile-editor-trait-count-hint",
                ("current", selectionCount),
                ("max", maximum)),
            FontColorOverride = Color.Gray,
        });
    }
}
