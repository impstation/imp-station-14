using Content.Client._Impstation.Interactions.Carving.Systems;
using Content.Shared._Impstation.Interactions.Carving.Components;
using Content.Shared._Impstation.Interactions.Carving.Events;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Client._Impstation.Interactions.Carving.UI;

[GenerateTypedNameReferences]
public sealed partial class PatternStorageControl : ScrollContainer
{
    [Dependency] private readonly IEntityManager _entityManager = default!;

    private readonly CarvingSystem _carvingSystem;

    private EntityUid _owner;

    private int _buttonPerLine = 4;
    private float _buttonSpacing = 0;

    public PatternStorageControl()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _carvingSystem = _entityManager.System<CarvingSystem>();
    }

    public void SetOwner(EntityUid owner)
    {
        _owner = owner;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (_owner == EntityUid.Invalid ||
            _entityManager.Deleted(_owner) ||
            !_entityManager.TryGetComponent<CarvableComponent>(_owner, out var carves))
            return;

        CarveList.RemoveAllChildren();

        var children = new List<PatternDisplay>();
        var grid = new GridContainer();
        grid.Columns = _buttonPerLine;
        AddCarveButton(carves.Carves, grid);
        CarveList.AddChild(grid);
    }

    private void AddCarveButton(HashSet<SpriteSpecifier> carves, GridContainer container)
    {
        foreach (var carve in carves)
        {
            var control = new PatternDisplay(carve, CarveList.Size.X / _buttonPerLine - _buttonSpacing);
            container.AddChild(control);
            control.OnSelect += SelectPattern;
        }
    }

    private void SelectPattern(CarvingPatternEntry entry)
    {

    }
}
