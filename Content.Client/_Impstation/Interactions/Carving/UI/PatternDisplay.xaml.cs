using Content.Shared._Impstation.Interactions.Carving.Events;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;
using System.Numerics;

namespace Content.Client._Impstation.Interactions.Carving.UI;

[GenerateTypedNameReferences]
public sealed partial class PatternDisplay : Button
{
    [Dependency] private readonly IEntityManager _entManager = default!;

    public event Action<CarvingPatternEntry>? OnSelect;

    public PatternDisplay(SpriteSpecifier sprite, float size = 16)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        var spriteSys = _entManager.System<SpriteSystem>();
        Icon.Texture = spriteSys.Frame0(sprite);
        //Button.SetSize = new Vector2(size, size);

        OnPressed += _ => OnSelect?.Invoke(new CarvingPatternEntry(sprite));
    }
}
