using Content.Client.UserInterface.Controls;
using Content.Shared._Impstation.Interactions.Carving.Components;
using Content.Shared._Impstation.Interactions.Carving.Events;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Client._Impstation.Interactions.Carving.UI;

[GenerateTypedNameReferences]
public sealed partial class CarvingInterface : FancyWindow
{
    [Dependency] private readonly IEntityManager _entityManager = default!;
    [Dependency] private readonly IPrototypeManager _prototypeManager = default!;

    public Action<CarvedEvent>? Carve;

    private readonly SpriteSystem _spriteSystem;

    private EntityUid _owner;

    private int _buttonPerLine = 4;
    private float _buttonSpacing = 0;

    private SpriteSpecifier? _selectedCarve;
    private string _customName = "";

    public CarvingInterface()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _spriteSystem = _entityManager.System<SpriteSystem>();

        Name.OnTextChanged += _ => OnNameEdit();
    }

    public void Display(EntityUid owner)
    {
        if (!_entityManager.TryGetComponent<SpriteComponent>(owner, out var sprite) ||
            sprite.Icon == null)
            return;

        _owner = owner;

        Carved.Texture = sprite.Icon.TextureFor(Direction.South);

        CarveButton.OnPressed += _ => Carve?.Invoke(new CarvedEvent
            (
            _selectedCarve,
            _customName
            ));
    }

    public void UpdatePatternListing()
    {
        if (_owner == EntityUid.Invalid ||
            _entityManager.Deleted(_owner) ||
            !_entityManager.TryGetComponent<CarvableComponent>(_owner, out var carves))
            return;

        CarveList.RemoveAllChildren();

        var children = new List<PatternDisplay>();
        var grid = new GridContainer();
        grid.Columns = _buttonPerLine;
        AddCarveButton(carves.Carves, grid);
    }

    private void AddCarveButton(HashSet<SpriteSpecifier> carves, GridContainer container)
    {
        foreach (var carve in carves)
        {
            var control = new PatternDisplay(carve, CarveList.Size.X / _buttonPerLine - _buttonSpacing);
            CarveList.AddChild(control);
            control.OnSelect += CarveSelect;
        }
    }

    private void OnNameEdit()
    {
        _customName = Name.Text;

        NameFiller.Visible = _customName.Length <= 0 ? true : false;
    }

    private void CarveSelect(CarvingPatternEntry pattern)
    {
        CarvedOverlay.Texture = _spriteSystem.Frame0(pattern.Sprite);
        _selectedCarve = pattern.Sprite;
    }
}
